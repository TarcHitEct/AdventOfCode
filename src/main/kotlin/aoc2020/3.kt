private fun main() {
    var list = input
        .split("\n")
        .map { it.trim() }
    val count = listOf(
        count(list, 1, 1),
        count(list, 3, 1),
        count(list, 5, 1),
        count(list, 7, 1),
        count(list, 1, 2)
    ).reduce { a, b -> a * b }
    println(count)
}

private fun count(list: List<String>, right: Int, down: Int): Int {
    return list.indices.step(down).count {
        val line = list[it]
        line[(it / down * right) % line.length] == '#'
    }
}

